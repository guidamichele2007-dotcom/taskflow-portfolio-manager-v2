import { EvolutionStage, PlantDefinition, Rarity } from '../types';

const RARITY_GOLD_COST: Record<Rarity, number> = {
  Comune: 500,
  NonComune: 1200,
  Raro: 3000,
  Epico: 7500,
  Leggendario: 18000,
  Mitico: 30000,
};

/** Genera la progressione Seme -> Fiorita -> Ancestrale standard (vedi docs/gdd/04). */
function standardEvolutions(rarity: Rarity, biomeMaterial = 'Materiale di Bioma'): EvolutionStage[] {
  const goldCost = RARITY_GOLD_COST[rarity];
  return [
    { stage: 'Seme', statMultiplier: 1, goldSeedCost: 0, humusCost: 0 },
    { stage: 'Fiorita', statMultiplier: 1.25, goldSeedCost: goldCost, humusCost: 20 },
    {
      stage: 'Ancestrale',
      statMultiplier: 1.6,
      goldSeedCost: goldCost * 2,
      humusCost: 60,
      biomeMaterial,
    },
  ];
}

